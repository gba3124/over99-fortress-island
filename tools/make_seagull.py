#!/usr/bin/env python3
"""The seagull helper's body (HtfFortress/Models/Seagull.obj): a small low-poly gull in the game's flat palette.

Written procedurally (no Blender needed) because it is a handful of flat shapes: body and head, a beak, two eyes,
two swept wings with grey tips, and a tail. Forward is +Z (the helper's root is turned to its Yaw); Y up; about 1.2 m
of wingspan and 0.55 m from beak to tail, so it reads at the helpers' 0.82 scale next to a person.

    python3 tools/make_seagull.py
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "HtfFortress", "Models", "Seagull.obj")

verts = []
faces = {}  # material -> triangles (1-based indices)


def v(x, y, z):
    verts.append((x, y, z))
    return len(verts)


def tri(mat, a, b, c):
    faces.setdefault(mat, []).append((a, b, c))


def quad(mat, a, b, c, d):
    tri(mat, a, b, c)
    tri(mat, a, c, d)


def ellipsoid(mat, cx, cy, cz, rx, ry, rz, seg=10, ring=6):
    top = v(cx, cy + ry, cz)
    bottom = v(cx, cy - ry, cz)
    rows = []
    for iy in range(1, ring):
        t = math.pi * iy / ring
        y = cy + ry * math.cos(t)
        r = math.sin(t)
        rows.append([v(cx + rx * r * math.cos(2 * math.pi * ix / seg), y,
                       cz + rz * r * math.sin(2 * math.pi * ix / seg)) for ix in range(seg)])
    for ix in range(seg):  # pole fans
        tri(mat, top, rows[0][(ix + 1) % seg], rows[0][ix])
        tri(mat, bottom, rows[-1][ix], rows[-1][(ix + 1) % seg])
    for iy in range(len(rows) - 1):
        for ix in range(seg):
            quad(mat, rows[iy][ix], rows[iy][(ix + 1) % seg], rows[iy + 1][(ix + 1) % seg], rows[iy + 1][ix])


# body (a little longer than tall), head at the front, eyes either side
ellipsoid("GullWhite", 0.0, 0.30, 0.00, 0.105, 0.100, 0.235, 12, 7)
ellipsoid("GullWhite", 0.0, 0.415, 0.205, 0.075, 0.072, 0.078, 10, 6)
for s in (-1, 1):
    ellipsoid("GullEye", s * 0.052, 0.440, 0.240, 0.014, 0.014, 0.014, 6, 3)

# beak: a small cone pointing +Z
base = [(0.030 * math.cos(2 * math.pi * i / 6), 0.405 + 0.030 * math.sin(2 * math.pi * i / 6), 0.262) for i in range(6)]
tip = v(0.0, 0.398, 0.372)
ring = [v(*p) for p in base]
for i in range(6):
    tri("GullBeak", ring[i], ring[(i + 1) % 6], tip)
tri("GullBeak", ring[0], ring[2], ring[4])
tri("GullBeak", ring[1], ring[3], ring[5])

# wings: a white inner panel and a grey outer one, swept back a little
for s in (-1, 1):
    a = v(s * 0.080, 0.305, 0.095)   # inner front
    b = v(s * 0.080, 0.305, -0.085)  # inner back
    c = v(s * 0.340, 0.350, -0.010)  # mid front
    d = v(s * 0.340, 0.350, -0.180)  # mid back
    e = v(s * 0.555, 0.372, -0.045)  # tip front
    f = v(s * 0.555, 0.372, -0.215)  # tip back
    if s > 0:  # mirroring flips the winding; keep every wing facing up
        quad("GullWhite", a, c, d, b)
        quad("GullGrey", c, e, f, d)
    else:
        quad("GullWhite", b, d, c, a)
        quad("GullGrey", d, f, e, c)

# tail: a flat grey wedge
a = v(-0.055, 0.285, -0.205)
b = v(0.055, 0.285, -0.205)
c = v(0.0, 0.275, -0.365)
tri("GullGrey", a, b, c)

mats = {
    "GullWhite": (0.930, 0.930, 0.900),
    "GullGrey": (0.620, 0.660, 0.700),
    "GullBeak": (0.950, 0.620, 0.160),
    "GullEye": (0.070, 0.070, 0.090),
}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("# Seagull helper - generated by tools/make_seagull.py\n")
    f.write("mtllib Seagull.mtl\n")
    f.write("o Seagull\n")
    for x, y, z in verts:
        f.write(f"v {x:.6f} {y:.6f} {z:.6f}\n")
    for mat in ("GullWhite", "GullGrey", "GullBeak", "GullEye"):
        f.write(f"usemtl {mat}\n")
        for a, b, c in faces.get(mat, []):
            f.write(f"f {a} {b} {c}\n")

with open(os.path.join(HERE, "..", "HtfFortress", "Models", "Seagull.mtl"), "w", encoding="utf-8") as f:
    f.write("# Seagull helper - generated by tools/make_seagull.py\n")
    for name, (r, g, b) in mats.items():
        f.write(f"newmtl {name}\nKd {r:.6f} {g:.6f} {b:.6f}\nKe 0.000000 0.000000 0.000000\n\n")

print(f"wrote {OUT}: {len(verts)} vertices, {sum(len(t) for t in faces.values())} triangles")


# ---------- sitting in its nest (Helpers, State 5): SeagullSit is the same bird with its wings folded along its back, the
# black tips crossed over the tail; SeagullHead is its head on its own, its origin at the neck (NECK, in SeagullSit's
# space), so the helper code can turn it to look round and lift it to call. ----------
NECK = (0.0, 0.37, 0.15)


def ellipsoid_turned(mat, c, r, yaw, pitch=0.0, seg=10, ring=6):
    # ellipsoid() turned about its centre: yaw about Y (+ turns the front toward +X), then pitch about X (+ lifts the front).
    first = len(verts)
    ellipsoid(mat, c[0], c[1], c[2], r[0], r[1], r[2], seg, ring)
    cy, sy, cp, sp = math.cos(math.radians(yaw)), math.sin(math.radians(yaw)), math.cos(math.radians(pitch)), math.sin(math.radians(pitch))
    for i in range(first, len(verts)):
        x, y, z = verts[i][0] - c[0], verts[i][1] - c[1], verts[i][2] - c[2]
        y, z = y * cp + z * sp, -y * sp + z * cp
        x, z = x * cy + z * sy, -x * sy + z * cy
        verts[i] = (c[0] + x, c[1] + y, c[2] + z)


def save(name, order):
    with open(os.path.join(HERE, "..", "HtfFortress", "Models", name + ".obj"), "w", encoding="utf-8") as f:
        f.write(f"# {name} - generated by tools/make_seagull.py\n")
        f.write(f"mtllib {name}.mtl\n")
        f.write(f"o {name}\n")
        for x, y, z in verts:
            f.write(f"v {x:.6f} {y:.6f} {z:.6f}\n")
        for mat in order:
            f.write(f"usemtl {mat}\n")
            for a, b, c in faces.get(mat, []):
                f.write(f"f {a} {b} {c}\n")
    with open(os.path.join(HERE, "..", "HtfFortress", "Models", name + ".mtl"), "w", encoding="utf-8") as f:
        f.write(f"# {name} - generated by tools/make_seagull.py\n")
        for mat in order:
            r, g, b = mats[mat]
            f.write(f"newmtl {mat}\nKd {r:.6f} {g:.6f} {b:.6f}\nKe 0.000000 0.000000 0.000000\n\n")
    print(f"wrote {name}: {len(verts)} vertices, {sum(len(t) for t in faces.values())} triangles")


mats["GullTip"] = (0.150, 0.150, 0.170)

verts.clear()
faces.clear()
ellipsoid("GullWhite", 0.0, 0.30, 0.00, 0.105, 0.100, 0.235, 12, 7)        # the body, as in flight
ellipsoid("GullWhite", 0.0, 0.365, 0.150, 0.062, 0.068, 0.065, 8, 5)       # the neck the head turns on
for s in (-1, 1):
    ellipsoid_turned("GullGrey", (s * 0.084, 0.338, -0.065), (0.034, 0.066, 0.205), s * 6.0, -4.0, 10, 6)  # a folded wing
    ellipsoid_turned("GullTip", (s * 0.040, 0.338, -0.285), (0.024, 0.030, 0.105), s * 12.0, -3.0, 8, 5)    # its black tip
a = v(-0.055, 0.285, -0.205)  # the tail, as in flight, under the crossed tips
b = v(0.055, 0.285, -0.205)
c = v(0.0, 0.275, -0.365)
tri("GullGrey", a, b, c)
save("SeagullSit", ("GullWhite", "GullGrey", "GullTip"))

verts.clear()
faces.clear()
nx, ny, nz = NECK
ellipsoid("GullWhite", 0.0, 0.415 - ny, 0.205 - nz, 0.075, 0.072, 0.078, 10, 6)
for s in (-1, 1):
    ellipsoid("GullEye", s * 0.052, 0.440 - ny, 0.240 - nz, 0.014, 0.014, 0.014, 6, 3)
base = [(0.030 * math.cos(2 * math.pi * i / 6), 0.405 - ny + 0.030 * math.sin(2 * math.pi * i / 6), 0.262 - nz) for i in range(6)]
tip = v(0.0, 0.398 - ny, 0.372 - nz)
ring = [v(*p) for p in base]
for i in range(6):
    tri("GullBeak", ring[i], ring[(i + 1) % 6], tip)
tri("GullBeak", ring[0], ring[2], ring[4])
tri("GullBeak", ring[1], ring[3], ring[5])
save("SeagullHead", ("GullWhite", "GullBeak", "GullEye"))
